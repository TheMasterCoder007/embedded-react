// Emits the generated C for baked assets: one .c with the image pixel arrays + font BitmapFont data,
// and one .h declaring er_register_assets(). The .c depends only on the public engine header
// (er_scene.h, which exposes both er_image_load/er_font_register and the BitmapFont format), so it
// drops into any target's build the same way the bundle does.

const ARGB8888_HEX_DIGITS = 8;
const RGB565_HEX_DIGITS = 4;
const BYTE_HEX_DIGITS = 2;
const ARGB8888_WORDS_PER_LINE = 8;
const RGB565_WORDS_PER_LINE = 12;
const BITMAP_BYTES_PER_LINE = 16;
const DEFAULT_BPP = 4;

/** Sanitizes an asset/family name into a C identifier fragment. */
function cIdent(name) {
  let identifier = String(name).replace(/[^0-9a-zA-Z_]/g, '_');
  if (identifier && /[0-9]/.test(identifier[0])) identifier = '_' + identifier;
  return identifier || '_asset';
}

/** Formats an array of byte/word strings into wrapped C initializer lines. */
function rows(values, perLine, indent = '    ') {
  const lines = [];
  for (let start = 0; start < values.length; start += perLine) {
    lines.push(indent + values.slice(start, start + perLine).join(', ') + ',');
  }
  return lines.join('\n');
}

/** Emits the GlyphInfo designated-initializer for one glyph. */
function glyphInit(glyph) {
  return (
    `{ .bitmap_offset = ${glyph.bitmapOffset}, .width = ${glyph.width}, .height = ${glyph.height}, ` +
    `.x_offset = ${glyph.xOffset}, .y_offset = ${glyph.yOffset}, .advance = ${glyph.advance} }`
  );
}

/**
 * Builds the .c and .h text for a set of baked images and fonts.
 *
 * @param {object} opts
 * @param {string} opts.headerName       Basename of the .h (for the .c's #include).
 * @param {Array<object>} [opts.images]  Results from bakeImage().
 * @param {Array<object>} [opts.fonts]   Results from bakeFont().
 * @returns {{c:string, h:string}}
 */
export function emitAssetsC({headerName, images = [], fonts = []}) {
  const guard = 'ER_' + cIdent(headerName).toUpperCase();
  const header =
    `/* Generated by packages/embedded-react/assets — DO NOT EDIT. */\n` +
    `#ifndef ${guard}\n#define ${guard}\n\n` +
    `#ifdef __cplusplus\nextern "C"\n{\n#endif\n\n` +
    `    /** @brief Registers every baked image and font with the engine (call once at boot, after\n` +
    `     *         embedded_renderer_set_backend()). */\n` +
    `    void er_register_assets(void);\n\n` +
    `#ifdef __cplusplus\n}\n#endif\n\n` +
    `#endif\n`;

  const lines = [];
  lines.push(
    `/* Generated by packages/embedded-react/assets — DO NOT EDIT. */`,
  );
  lines.push(
    `/* Images: premultiplied ARGB8888 (or RGB565 when baked 16-bit), referenced by pointer. Fonts: baked BitmapFont per size. */`,
  );
  lines.push(``);
  lines.push(`#include "${headerName}"`);
  lines.push(
    `#include "er_scene.h" /* er_image_load, er_font_register, BitmapFont */`,
  );
  lines.push(`#include <stddef.h>`);
  lines.push(`#include <stdint.h>`);
  lines.push(``);

  // --- Images ---------------------------------------------------------------------------------
  for (const image of images) {
    const identifier = cIdent(image.name);
    const is565 = image.format === 'rgb565';
    const hex = Array.from(
      image.pixels,
      pixel =>
        '0x' +
        pixel
          .toString(16)
          .toUpperCase()
          .padStart(is565 ? RGB565_HEX_DIGITS : ARGB8888_HEX_DIGITS, '0') +
        'u',
    );
    lines.push(
      `/* image "${image.name}" — ${image.width}x${image.height}${is565 ? ' (RGB565)' : ''} */`,
    );
    lines.push(
      `static const ${is565 ? 'uint16_t' : 'uint32_t'} ${identifier}_px[] = {`,
    );
    lines.push(
      rows(hex, is565 ? RGB565_WORDS_PER_LINE : ARGB8888_WORDS_PER_LINE),
    );
    lines.push(`};`);
    lines.push(``);
  }

  // --- Fonts ----------------------------------------------------------------------------------
  const fontRegistrations = [];
  for (const font of fonts) {
    const familyIdentifier = cIdent(font.family);
    lines.push(
      `/* font "${font.family}" — ${font.sizes.map(size => `${size.pixelSize}px`).join(', ')} */`,
    );
    emitFontSizes(lines, font, familyIdentifier, 'static const '); // file-local: only er_register_assets refers to these
    for (const size of font.sizes) {
      fontRegistrations.push(
        `    er_font_register(${JSON.stringify(font.family)}, &g_font_${familyIdentifier}_${size.pixelSize});`,
      );
    }
  }

  // --- Registration entry point ---------------------------------------------------------------
  lines.push(`void er_register_assets(void)`);
  lines.push(`{`);
  for (const image of images) {
    const loadFunction =
      image.format === 'rgb565' ? 'er_image_load_rgb565' : 'er_image_load';
    lines.push(
      `    ${loadFunction}(${JSON.stringify(image.name)}, ${cIdent(image.name)}_px, ${image.width}, ${image.height});`,
    );
  }
  for (const registration of fontRegistrations) lines.push(registration);
  if (images.length === 0 && fontRegistrations.length === 0) {
    lines.push(`    /* no baked assets */`);
  }
  lines.push(`}`);
  lines.push(``);

  return {c: lines.join('\n'), h: header};
}

/** Emits the per-size BitmapFont blocks (bitmap + glyphs + extras + struct) for one font. */
function emitFontSizes(lines, font, symbol, fontStorage) {
  for (const size of font.sizes) {
    const prefix = `s_${symbol}_${size.pixelSize}`;
    const hex = size.bitmap.map(
      byte =>
        '0x' + byte.toString(16).toUpperCase().padStart(BYTE_HEX_DIGITS, '0'),
    );
    lines.push(
      `static const uint8_t ${prefix}_bitmap[${size.bitmap.length || 1}] = {`,
    );
    lines.push(
      size.bitmap.length ? rows(hex, BITMAP_BYTES_PER_LINE) : '    0x00,',
    );
    lines.push(`};`);
    lines.push(``);

    lines.push(
      `static const GlyphInfo ${prefix}_glyphs[${size.dense.length}] = {`,
    );
    for (const glyph of size.dense) lines.push(`    ${glyphInit(glyph)},`);
    lines.push(`};`);
    lines.push(``);

    if (size.extras.length) {
      lines.push(
        `static const ExtraGlyph ${prefix}_extras[${size.extras.length}] = {`,
      );
      for (const extra of size.extras) {
        lines.push(
          `    { .codepoint = 0x${extra.codepoint.toString(16).toUpperCase()}, .info = ${glyphInit(extra.info)} },`,
        );
      }
      lines.push(`};`);
      lines.push(``);
    }

    lines.push(
      `${fontStorage}BitmapFont g_font_${symbol}_${size.pixelSize} = {`,
    );
    lines.push(`    .bitmap       = ${prefix}_bitmap,`);
    lines.push(`    .glyphs       = ${prefix}_glyphs,`);
    lines.push(
      `    .extras       = ${size.extras.length ? `${prefix}_extras` : 'NULL'},`,
    );
    lines.push(`    .extras_count = ${size.extras.length},`);
    lines.push(
      `    .first        = 0x${size.first.toString(16).toUpperCase()},`,
    );
    lines.push(
      `    .last         = 0x${size.last.toString(16).toUpperCase()},`,
    );
    lines.push(`    .pixel_size   = ${size.pixelSize},`);
    lines.push(`    .line_height  = ${size.lineHeight},`);
    lines.push(`    .baseline     = ${size.baseline},`);
    lines.push(`    .format       = ${size.bpp},`);
    lines.push(`};`);
    lines.push(``);
  }
}

/**
 * Emits the engine's built-in font translation unit (font_data.c format): the per-size BitmapFont
 * structs plus the `g_<symbol>_sizes[]` array + `_count` that font_registry.c falls back to. Depends
 * only on font_bitmap.h. Symbol must be 'inter' to satisfy the extern decls in font_bitmap.h.
 *
 * @param {object} opts
 * @param {object} opts.font        Result of bakeFont().
 * @param {string} [opts.symbol]    C symbol prefix (default 'inter').
 * @param {string} [opts.sourceName] Source font filename, for the header comment.
 * @returns {string} The .c source text.
 */
export function emitBuiltinFont({font, symbol = 'inter', sourceName = ''}) {
  const sizeList = font.sizes.map(size => size.pixelSize).join(',');
  const bpp = font.sizes[0] ? font.sizes[0].bpp : DEFAULT_BPP;
  const lines = [];
  lines.push(
    `/* AUTO-GENERATED by packages/embedded-react/assets/build-builtin-font.mjs — do not edit by hand.`,
  );
  lines.push(` * Source : ${sourceName}`);
  lines.push(` * Sizes  : ${sizeList}  (bpp ${bpp}, family "${font.family}")`);
  lines.push(
    ` * Regenerate: cd packages/embedded-react && npm run build:builtin-font`,
  );
  lines.push(` */`);
  lines.push(`#include "font_bitmap.h"`);
  lines.push(`#include <stddef.h>`);
  lines.push(``);

  emitFontSizes(lines, font, symbol, 'const '); // file-scope const: referenced by g_<symbol>_sizes

  lines.push(`const BitmapFont *const g_${symbol}_sizes[] = {`);
  for (const size of font.sizes)
    lines.push(`    &g_font_${symbol}_${size.pixelSize},`);
  lines.push(`};`);
  lines.push(
    `const size_t g_${symbol}_sizes_count = sizeof(g_${symbol}_sizes) / sizeof(g_${symbol}_sizes[0]);`,
  );
  lines.push(``);
  return lines.join('\n');
}
